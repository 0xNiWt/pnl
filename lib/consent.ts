export type RatingConsent = {
    consentedAt: string | null;
    version: string | null;
    revokedAt: string | null;
};

/** Чи можна враховувати учня в рейтингах: згода є і її не відкликали. */
export function hasRatingConsent(consent: RatingConsent | null | undefined): boolean {
    if (!consent) return false;
    if (consent.revokedAt) return false;
    return Boolean(consent.consentedAt);
}
