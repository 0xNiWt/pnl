-- Закладає шкалу олімпіадних балів із чинного Положення (пп. 10.1.10.1
-- та 10.1.10.2). Досі шкала була тимчасовою: у старій редакції Статуту
-- п. 10.7.6 стояв як [ДОРОБИТИ], тож значення вигадували на місці.
--
-- Предметні олімпіади (п. 10.1.10.1):
--   Районний        5 / 3 / 1
--   Міський        15 / 11 / 7
--   Всеукраїнський 47 / 35 / 23
--   Міжнародний   143 / 107 / 71
--
-- МАН, конкурс-захист (п. 10.1.10.2):
--   Міський        30 / 22 / 14
--   Всеукраїнський 94 / 70 / 26
--
-- УВАГА, розбіжність у самому Положенні. П. 10.1.10 каже, що МАН оцінюється
-- з коефіцієнтом ×2 відносно олімпіади того самого етапу. Для міського етапу
-- це сходиться точно (15/11/7 × 2 = 30/22/14). Для всеукраїнського сходяться
-- лише перші два ступені (47×2 = 94, 35×2 = 70), а третій за таблицею — 26,
-- тоді як ×2 дає 46. Тут закладено те число, що надруковане в таблиці (26).
-- Якщо 26 — друкарська помилка, досить виправити один рядок нижче.
--
-- «Участь» (place = 0) балів не дає: Положення нараховує бали лише за
-- призові місця (п. 10.1.10.3).
--
-- Етапи 'school', 'region' і збірний 'man' у чинній шкалі відсутні. Рядки
-- за ними навмисно не видаляємо: на них можуть посилатися раніше внесені
-- здобутки, а бали в olympiad_results зберігаються знімком на момент
-- внесення й від шкали вже не залежать.
--
-- Міграція безпечна для повторного запуску.

insert into public.olympiad_scale (level, place, points) values
  -- Предметні олімпіади, п. 10.1.10.1
  ('district',      1,   5),
  ('district',      2,   3),
  ('district',      3,   1),
  ('district',      0,   0),

  ('city',          1,  15),
  ('city',          2,  11),
  ('city',          3,   7),
  ('city',          0,   0),

  ('national',      1,  47),
  ('national',      2,  35),
  ('national',      3,  23),
  ('national',      0,   0),

  ('international', 1, 143),
  ('international', 2, 107),
  ('international', 3,  71),
  ('international', 0,   0),

  -- Конкурс-захист МАН, п. 10.1.10.2
  ('man-city',      1,  30),
  ('man-city',      2,  22),
  ('man-city',      3,  14),
  ('man-city',      0,   0),

  ('man-national',  1,  94),
  ('man-national',  2,  70),
  ('man-national',  3,  26),   -- за таблицею Положення; за правилом ×2 було б 46
  ('man-national',  0,   0)
on conflict (level, place) do update set points = excluded.points;
