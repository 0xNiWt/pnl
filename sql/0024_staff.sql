-- 0024_staff.sql
--
-- Педагогічний колектив (сторінка «Педагоги») переїжджає з коду в базу,
-- щоб адміністрація могла додавати й редагувати вчителів з кабінету.
--
-- Кафедра — це просто назва в рядку вчителя: кафедри окремої таблиці не
-- мають. Порядок кафедр задає dept_order, порядок людей усередині — sort_order.
--
-- Таблиця навмисно зветься staff_members: порожня таблиця staff з іншими
-- колонками вже є в базі з давніх часів, і ми її не чіпаємо.
--
-- Міграція безпечна для повторного запуску: таблиця створюється за потреби,
-- а початковий список додається лише тоді, коли таблиця порожня.

create table if not exists public.staff_members (
  id         uuid        primary key default gen_random_uuid(),
  department text        not null,
  dept_order int         not null default 100,
  name       text        not null,
  position   text        not null default '',
  photo_url  text,
  sort_order int         not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists staff_members_department_idx on public.staff_members (dept_order, sort_order);

alter table public.staff_members enable row level security;

-- Список педагогів публічний: його показує сторінка «Педагоги».
drop policy if exists staff_members_read on public.staff_members;
create policy staff_members_read
  on public.staff_members for select
  using (true);

-- Редагують адміністрація (owner) і модератори — ті самі, хто веде книгу
-- пам'яті та таблиці олімпіад.
drop policy if exists staff_members_manage on public.staff_members;
create policy staff_members_manage
  on public.staff_members for all
  to authenticated
  using (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and p.roles::text[] && array['owner', 'moderator']
    )
  )
  with check (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and p.roles::text[] && array['owner', 'moderator']
    )
  );

grant select on public.staff_members to anon, authenticated;
grant insert, update, delete on public.staff_members to authenticated;

