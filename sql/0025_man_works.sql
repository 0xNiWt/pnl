-- Роботи МАН (Мала академія наук) — окрема вкладка в розділі «Ліцей».
-- Кожен запис: тема роботи, автор і клас, наукові керівники, відділення
-- та секція, короткий опис, розповідь про роботу, фото з дослідження
-- і сам файл роботи.
--
-- Читати може будь-хто, редагувати — адміністрація та модератори
-- (ті самі, хто веде книгу пам'яті й педагогічний колектив).
--
-- Міграція безпечна для повторного запуску: таблиця створюється за
-- потреби, початкові чотири роботи додаються лише в порожню таблицю.

create table if not exists public.man_works (
  id          uuid        primary key default gen_random_uuid(),
  title       text        not null,
  author      text        not null,
  author_info text,
  supervisor  text,
  section     text,
  year        text,
  summary     text,
  description text,
  photo_url   text,
  file_url    text,
  sort_order  int         not null default 100,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists man_works_sort_idx on public.man_works (sort_order);

alter table public.man_works enable row level security;

drop policy if exists man_works_read on public.man_works;
create policy man_works_read
  on public.man_works for select
  using (true);

drop policy if exists man_works_manage on public.man_works;
create policy man_works_manage
  on public.man_works for all
  to authenticated
  using (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and p.roles::text[] && array['owner', 'moderator']
    )
  )
  with check (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and p.roles::text[] && array['owner', 'moderator']
    )
  );

grant select on public.man_works to anon, authenticated;
grant insert, update, delete on public.man_works to authenticated;

