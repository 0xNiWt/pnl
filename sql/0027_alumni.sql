-- 0027_alumni.sql
--
-- Випускники ліцею: окрема вкладка у верхньому меню, оформлена як новини.
-- Кожен запис: імʼя, ким людина є зараз, роки навчання в ліцеї, розповідь
-- і фото.
--
-- Читати може будь-хто, редагувати — адміністрація та модератори.
-- Міграція безпечна для повторного запуску: початковий список додається
-- лише в порожню таблицю.

create table if not exists public.alumni (
  id         uuid        primary key default gen_random_uuid(),
  name       text        not null,
  headline   text,
  years      text,
  bio        text,
  photo_url  text,
  link_url   text,
  sort_order int         not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists alumni_sort_idx on public.alumni (sort_order);

alter table public.alumni enable row level security;

drop policy if exists alumni_read on public.alumni;
create policy alumni_read
  on public.alumni for select
  using (true);

drop policy if exists alumni_manage on public.alumni;
create policy alumni_manage
  on public.alumni for all
  to authenticated
  using (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and p.roles::text[] && array['owner', 'moderator']
    )
  )
  with check (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and p.roles::text[] && array['owner', 'moderator']
    )
  );

grant select on public.alumni to anon, authenticated;
grant insert, update, delete on public.alumni to authenticated;

